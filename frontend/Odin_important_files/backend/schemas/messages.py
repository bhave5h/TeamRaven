from typing import Literal, Any
from pydantic import BaseModel, Field
import uuid
from datetime import datetime

# ==========================================
# Citations & Verbatim Proofs
# ==========================================

class Citation(BaseModel):
    """Canonical citation anchor referencing exact raw contract text."""
    doc_id: str = Field(description="Document ID without extension, e.g., 'A1', 'B1', 'STD'")
    section: str = Field(description="Section reference, e.g., '§3.1', 'Section 4.3'")
    quote: str = Field(description="Exact verbatim substring from the .txt file")
    verified: bool = Field(default=False, description="True if verified by CitationGuardrail")

# ==========================================
# Extraction Schemas (Thor / Parser)
# ==========================================

class ExtractedObligation(BaseModel):
    """A discrete obligation or covenant extracted from a clause."""
    obligation_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    doc_id: str
    section: str
    category: Literal["payment", "service_level", "termination", "liability", "confidentiality", "insurance", "general"]
    obligor: str = Field(description="Party bound by the obligation")
    obligee: str = Field(description="Party owed the obligation")
    summary: str
    deadline_rule: str | None = Field(default=None, description="e.g. '15 business days following invoice'")
    financial_formula: str | None = Field(default=None, description="e.g. '15% credit of monthly billing'")
    citation: Citation
    confidence: Literal["high", "medium", "low"] = "high"
    source_tag: Literal["sourced", "inferred"] = "sourced"
    is_ambiguous: bool = False
    ambiguity_reason: str | None = None

class ExtractionResult(BaseModel):
    """Collection of extracted entities and obligations for a contract."""
    doc_id: str
    title: str
    effective_date: str | None = None
    term_length: str | None = None
    counterparty: str | None = None
    governing_law: str | None = None
    notice_address: str | None = None
    missing_exhibits: list[str] = Field(default_factory=list)
    blank_fields: list[str] = Field(default_factory=list)
    obligations: list[ExtractedObligation] = Field(default_factory=list)

# ==========================================
# Timeline & Exposure Schemas (Norns / Timeline Engine)
# ==========================================

class TimelineMilestone(BaseModel):
    """A past, active, or future deadline tied to a simulated checkpoint."""
    milestone_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    contract_id: str
    title: str
    target_date: str
    due_checkpoint: str
    status: Literal["completed", "pending", "overdue", "time_barred", "projected"]
    penalty_rate_per_day: float | None = None
    accumulated_penalty: float | None = None
    citation: Citation | None = None
    notes: str = ""

class ExposureSummary(BaseModel):
    """Amounts explicitly recorded in the active upload."""
    checkpoint_date: str
    total_exposure_at_risk: float | None = None
    breakdown_by_contract: dict[str, float] = Field(default_factory=dict)
    recorded_transaction_count: int = 0
    recorded_transaction_total: float = 0.0
    flagged_transaction_count: int = 0
    flagged_transaction_total: float = 0.0

# ==========================================
# Operational Events (Heimdall / Event Ingester)
# ==========================================

class OperationalEvent(BaseModel):
    """An event from events_drop1.jsonl or events_drop2.jsonl."""
    event_id: str
    timestamp: str
    drop_number: int
    source: str
    event_type: str
    summary: str
    raw_payload: dict[str, Any] = Field(default_factory=dict)
    affected_contracts: list[str] = Field(default_factory=list)
    is_noise: bool = False
    noise_rationale: str | None = None
    mapped_clauses: list[Citation] = Field(default_factory=list)

# ==========================================
# Adversarial Findings & Debates (Loki, Heimdall, Tyr)
# ==========================================

class AdversarialAttack(BaseModel):
    """An adversarial risk finding generated by Loki."""
    attack_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    category: Literal["sla_gap", "liability_uncapped", "policy_lapse", "conflicting_terms", "maintenance_mismatch", "territory_conflict"]
    severity: Literal["critical", "high", "medium", "low"]
    affected_contracts: list[str]
    claim_summary: str
    counterparty_angle: str
    citations: list[Citation]
    confidence: Literal["high", "medium", "low"] = "high"
    source_tag: Literal["sourced", "inferred"] = "sourced"

class DebateTurn(BaseModel):
    """A turn in the Loki vs. Heimdall debate stream."""
    turn_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    round_number: int
    speaker: Literal["Loki", "Heimdall", "Tyr", "Thor", "Odin"]
    speaker_role: Literal["adversary", "event_monitor", "arbiter", "extractor", "orchestrator"]
    message_type: Literal["attack", "counter_evidence", "clarification_request", "clarification_response", "ruling", "source_event", "source_finding"]
    content: str
    citations: list[Citation] = Field(default_factory=list)
    timestamp: str = Field(default_factory=lambda: datetime.utcnow().isoformat())

class ArbitrationRuling(BaseModel):
    """Judicial resolution issued by Tyr."""
    ruling_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    issue: str
    verdict: Literal["TRUE", "FALSE", "INVALID", "NO_CREDIT", "SPLIT", "REQUIRES_SETTLEMENT", "PENDING_EVIDENCE"]
    rationale: str
    controlling_precedence: str | None = None
    binding_citations: list[Citation] = Field(default_factory=list)
    needs_human_approval: bool = False

# ==========================================
# Actionable Legal Notices (Tyr / Actions)
# ==========================================

class DraftedLegalNotice(BaseModel):
    """Formal notice ready for human review and signoff."""
    action_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    checkpoint: str
    action_type: Literal["breach_notice", "credit_claim", "credit_denial", "non_renewal_invalidation", "insurance_escalation", "evidence_review"]
    target_party: str
    target_address: str
    title: str
    subject_line: str
    letter_body: str
    binding_clauses: list[Citation] = Field(default_factory=list)
    deadline_to_send: str | None = None
    status: Literal["drafted", "approved", "rejected", "sent", "completed"] = "drafted"
    needs_human_approval: bool = True

# ==========================================
# Generic Inter-Agent Envelope (LangGraph Message)
# ==========================================

class AgentMessage(BaseModel):
    """Universal typed message schema for multi-agent coordination."""
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    run_id: str
    clock_position: str
    sender: str
    recipient: str
    msg_type: Literal[
        "task", "result", "clarification_query", "clarification_reply",
        "attack", "verification", "ruling", "alert", "action"
    ]
    payload: dict[str, Any] = Field(default_factory=dict)
    citations: list[Citation] = Field(default_factory=list)
    confidence: Literal["high", "medium", "low"] = "high"
    source_tag: Literal["sourced", "inferred"] = "sourced"
    parent_id: str | None = None
    timestamp: str = Field(default_factory=lambda: datetime.utcnow().isoformat())
